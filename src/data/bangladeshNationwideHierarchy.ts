// Helper to assemble an Upazila node
function upz(id: string, nameEn: string, nameBn: string, slug: string, mouzas?: MouzaNode[]): UpazilaNode {
  return {
    id: `upz-${id}`,
    nameEn,
    nameBn,
    eporchaSlug: slug,
    mouzas: mouzas || generateMouzasForUpazila(slug, nameEn, nameBn, 12),
  };
}

