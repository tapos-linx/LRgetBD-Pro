// Helper to create authentic Mouza nodes
export function createMouzaList(
  upazilaKey: string,
  entries: Array<{
    jlNo: string;
    nameEn: string;
    nameBn: string;
    unionEn: string;
    unionBn: string;
    khatians?: number;
    dags?: number;
  }>
): MouzaNode[] {
  return entries.map((e) => ({
    id: `mz-${upazilaKey}-${e.jlNo}-${e.nameEn.toLowerCase().replace(/[^a-z0-9]/g, '')}`,
    jlNo: e.jlNo,
    nameEn: e.nameEn,
    nameBn: e.nameBn,
    unionNameEn: e.unionEn,
    unionNameBn: e.unionBn,
    availableSurveys: ['CS', 'SA', 'RS', 'BS', 'MUTATION'],
    estimatedKhatians: e.khatians ?? 850,
    estimatedDags: e.dags ?? 1950,
    mapSheets: [1, 2],
  }));
}

